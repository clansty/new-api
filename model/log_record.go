func RecordErrorLog(c *gin.Context, userId int, channelId int, modelName string, tokenName string, content string, tokenId int, useTimeSeconds int,
	isStream bool, group string, other map[string]any) {
	logger.LogInfo(c, fmt.Sprintf("record error log: userId=%d, channelId=%d, modelName=%s, tokenName=%s, content=%s", userId, channelId, modelName, tokenName, content))
	username := c.GetString("username")
	requestId := c.GetString(common.RequestIdKey)
	otherStr := common.MapToJsonStr(other)
	// 判断是否需要记录 IP
	needRecordIp := false
	if settingMap, err := GetUserSetting(userId, false); err == nil {
		if settingMap.RecordIpLog {
			needRecordIp = true
		}
	}
	tokenRootId := c.GetInt("token_root_id")
	if tokenRootId == 0 {
		tokenRootId = tokenId
	}
	log := &Log{
		UserId:           userId,
		Username:         username,
		CreatedAt:        common.GetTimestamp(),
		Type:             LogTypeError,
		Content:          content,
		PromptTokens:     0,
		CompletionTokens: 0,
		TokenName:        tokenName,
		ModelName:        modelName,
		Quota:            0,
		ChannelId:        channelId,
		TokenId:          tokenId,
		TokenRootId:      tokenRootId,
		UseTime:          useTimeSeconds,
		IsStream:         isStream,
		Group:            group,
		Ip: func() string {
			if needRecordIp {
				return c.ClientIP()
			}
			return ""
		}(),
		RequestId: requestId,
		UserAgent: c.Request.UserAgent(),
		Other:     otherStr,
	}
	err := LOG_DB.Create(log).Error
	if err != nil {
		logger.LogError(c, "failed to record log: "+err.Error())
	}
}

type RecordConsumeLogParams struct {
	ChannelId        int            `json:"channel_id"`
	OriginalQuota    float64        `json:"original_quota"`
	PromptTokens     int            `json:"prompt_tokens"`
	CompletionTokens int            `json:"completion_tokens"`
	ModelName        string         `json:"model_name"`
	TokenName        string         `json:"token_name"`
	Quota            int            `json:"quota"`
	Content          string         `json:"content"`
	TokenId          int            `json:"token_id"`
	TokenRootId      int            `json:"token_root_id"`
	UseTimeSeconds   int            `json:"use_time_seconds"`
	IsStream         bool           `json:"is_stream"`
	Group            string         `json:"group"`
	Other            map[string]any `json:"other"`
}

func calculateRequestCost(channelId int, originalQuota float64) *float64 {
	if channelId <= 0 {
		return nil
	}
	channel, err := CacheGetChannel(channelId)
	if err != nil {
		return nil
	}
	rate, _ := channel.EffectiveUpstreamRateMultiplier()
	if rate == nil {
		return nil
	}
	cost := originalQuota * *rate
	return &cost
}

func RecordConsumeLog(c *gin.Context, userId int, params RecordConsumeLogParams) {
	if !common.LogConsumeEnabled {
		return
	}
	logger.LogInfo(c, fmt.Sprintf("record consume log: userId=%d, params=%s", userId, common.GetJsonString(params)))
	username := c.GetString("username")
	requestId := c.GetString(common.RequestIdKey)
	createdAt := common.GetTimestamp()
	otherStr := common.MapToJsonStr(params.Other)
	// 判断是否需要记录 IP
	needRecordIp := false
	if settingMap, err := GetUserSetting(userId, false); err == nil {
		if settingMap.RecordIpLog {
			needRecordIp = true
		}
	}
	tokenRootId := params.TokenRootId
	if tokenRootId == 0 {
		tokenRootId = c.GetInt("token_root_id")
	}
	if tokenRootId == 0 {
		tokenRootId = params.TokenId
	}
	log := &Log{
		UserId:           userId,
		Username:         username,
		CreatedAt:        createdAt,
		Type:             LogTypeConsume,
		Content:          params.Content,
		PromptTokens:     params.PromptTokens,
		CompletionTokens: params.CompletionTokens,
		TokenName:        params.TokenName,
		ModelName:        params.ModelName,
		Quota:            params.Quota,
		Cost:             calculateRequestCost(params.ChannelId, params.OriginalQuota),
		ChannelId:        params.ChannelId,
		TokenId:          params.TokenId,
		TokenRootId:      tokenRootId,
		UseTime:          params.UseTimeSeconds,
		IsStream:         params.IsStream,
		Group:            params.Group,
		Ip: func() string {
			if needRecordIp {
				return c.ClientIP()
			}
			return ""
		}(),
		RequestId: requestId,
		UserAgent: c.Request.UserAgent(),
		Other:     otherStr,
	}
	err := LOG_DB.Create(log).Error
	if err != nil {
		logger.LogError(c, "failed to record log: "+err.Error())
	}
	if common.DataExportEnabled {
		// 同步调用: LogQuotaData 内部只是加锁的 map 累加, 极快;
		// 若派生 goroutine 则在 graceful shutdown 时可能晚于 SaveQuotaDataCache 执行, 导致数据丢失.
		LogQuotaData(QuotaDataLogParams{
			UserID:    userId,
			Username:  username,
			ModelName: params.ModelName,
			Quota:     params.Quota,
			CreatedAt: createdAt,
			TokenUsed: params.PromptTokens + params.CompletionTokens,
			UseGroup:  params.Group,
			TokenID:   params.TokenId,
			ChannelID: params.ChannelId,
			NodeName:  common.NodeName,
		})
	}
}

type RecordTaskBillingLogParams struct {
	UserId        int
	LogType       int
	Content       string
	ChannelId     int
	ModelName     string
	Quota         int
	OriginalQuota *float64
	TokenId       int
	TokenRootId   int
	Group         string
	Other         map[string]any
}

func RecordTaskBillingLog(params RecordTaskBillingLogParams) {
	if params.LogType == LogTypeConsume && !common.LogConsumeEnabled {
		return
	}
	username, _ := GetUsernameById(params.UserId, false)
	tokenName := ""
	if params.TokenId > 0 {
		if token, err := GetTokenById(params.TokenId); err == nil {
			tokenName = token.Name
		}
	}
	createdAt := common.GetTimestamp()
	log := &Log{
		UserId:    params.UserId,
		Username:  username,
		CreatedAt: createdAt,
		Type:      params.LogType,
		Content:   params.Content,
		TokenName: tokenName,
		ModelName: params.ModelName,
		Quota:     params.Quota,
		Cost: func() *float64 {
			if params.OriginalQuota == nil {
				return nil
			}
			return calculateRequestCost(params.ChannelId, *params.OriginalQuota)
		}(),
		ChannelId:   params.ChannelId,
		TokenId:     params.TokenId,
		TokenRootId: params.TokenRootId,
		Group:       params.Group,
		Other:       common.MapToJsonStr(params.Other),
	}
	err := LOG_DB.Create(log).Error
	if err != nil {
		common.SysLog("failed to record task billing log: " + err.Error())
	}
	if params.LogType == LogTypeConsume && common.DataExportEnabled {
		LogQuotaData(QuotaDataLogParams{
			UserID:    params.UserId,
			Username:  username,
			ModelName: params.ModelName,
			Quota:     params.Quota,
			CreatedAt: createdAt,
			UseGroup:  params.Group,
			TokenID:   params.TokenId,
			ChannelID: params.ChannelId,
			NodeName:  common.NodeName,
		})
	}
}
